"""Certificate PDF download: lazy render + storage as a media asset.

PDFs are generated on first download, stored under the org's media
folder (owner_type="certificate", role="attachment" so they never enter
the member gallery), and the certificate's file_media_id points at them.
Subsequent downloads serve the stored bytes. No FastAPI, no CQL here.
"""

from __future__ import annotations

import hashlib
import json
from dataclasses import dataclass
from typing import TYPE_CHECKING
from uuid import UUID

from activities.interfaces import ActivityStore
from certificates.interfaces import (
    CertificateRenderer,
    CertificateStore,
    TemplateStore,
)
from core.exceptions import ForbiddenError, NotFoundError
from core.ids import uuid7
from core.media import MediaStore
from core.security import utcnow
from orgs.interfaces import MediaRepository, OrgRepository, UserDirectory
from rbac.interfaces import AccessControl

if TYPE_CHECKING:
    from activities.model import Activity
    from certificates.model import Certificate, CertificateTemplate

_PDF_MIME = "application/pdf"


@dataclass(frozen=True)
class CertificateFile:
    """Resolved download payload: suggested name plus raw PDF bytes."""

    filename: str
    content: bytes


class CertificateFileService:
    """Authorize and resolve (or lazily render) a certificate's PDF."""

    def __init__(
        self,
        certificates: CertificateStore,
        templates: TemplateStore,
        activities: ActivityStore,
        orgs: OrgRepository,
        users: UserDirectory,
        media: MediaRepository,
        store: MediaStore,
        renderer: CertificateRenderer,
        access: AccessControl,
    ) -> None:
        self._certificates = certificates
        self._templates = templates
        self._activities = activities
        self._orgs = orgs
        self._users = users
        self._media = media
        self._store = store
        self._renderer = renderer
        self._access = access

    def _authorize(self, org_id: UUID, student_id: UUID, actor: UUID) -> None:
        """The student owner or an org manager may download the file."""
        if actor == student_id:
            return
        org = self._orgs.get_by_id(org_id)
        allowed = org is not None and (
            getattr(org, "owner_id", None) == actor
            or self._access.has_permission(
                org_id, actor, "activity:manage"
            )
        )
        if not allowed:
            self._access.record(
                org_id, actor, "certificate.download",
                "certificate", None, "denied",
            )
            raise ForbiddenError(
                "Only the student or org managers can download this file."
            )

    def _stored(
        self, certificate: Certificate, serial: str
    ) -> CertificateFile | None:
        """Serve previously generated bytes when the asset still exists."""
        media_id = getattr(certificate, "file_media_id", None)
        if media_id is None:
            return None
        asset = self._media.get_asset(media_id)
        if asset is None:
            return None
        try:
            path = self._store.resolve(asset.file_url)
            if not path.is_file():
                return None
            return CertificateFile(
                filename=asset.original_name or f"certificate-{serial}.pdf",
                content=path.read_bytes(),
            )
        except (OSError, ValueError):
            return None

    def _background(
        self, template: CertificateTemplate | None
    ) -> bytes | None:
        """Resolve the template's background image bytes, best-effort."""
        media_id = getattr(template, "background_media_id", None)
        if template is None or media_id is None:
            return None
        asset = self._media.get_asset(media_id)
        if asset is None:
            return None
        try:
            path = self._store.resolve(asset.file_url)
            return path.read_bytes() if path.is_file() else None
        except (OSError, ValueError):
            return None

    @staticmethod
    def _layout(template: CertificateTemplate | None) -> dict:
        raw = getattr(template, "layout_json", None)
        if not raw:
            return {}
        try:
            parsed = json.loads(raw)
        except (TypeError, ValueError):
            return {}
        return parsed if isinstance(parsed, dict) else {}

    def _generate(
        self, certificate: Certificate, activity: Activity, org_id: UUID
    ) -> CertificateFile:
        """Render the PDF, persist it as an org media asset, link it."""
        brief = self._users.get_brief(certificate.student_id)
        org = self._orgs.get_by_id(org_id)
        template = (
            self._templates.get(certificate.template_id)
            if getattr(certificate, "template_id", None) is not None
            else None
        )
        content = self._renderer.render(
            student_name=(
                brief.full_name if brief is not None else "Sinh vi\u00ean"
            ),
            org_name=(org.name if org is not None else ""),
            activity_title=activity.title,
            serial_no=certificate.serial_no,
            issued_at=certificate.issued_at,
            background=self._background(template),
            layout=self._layout(template),
        )
        filename = f"certificate-{certificate.serial_no}.pdf"
        asset_id = uuid7()
        relative = self._store.save_typed(
            org_id, asset_id, _PDF_MIME, filename, content
        )
        self._media.create_asset(
            asset_id,
            org_id,
            relative,
            _PDF_MIME,
            len(content),
            utcnow(),
            role="attachment",
            file_hash=hashlib.sha256(content).hexdigest(),
            uploader_id=certificate.issued_by,
            original_name=filename,
            owner_type="certificate",
            owner_feed=False,
        )
        self._certificates.attach_file(certificate, asset_id, utcnow())
        return CertificateFile(filename=filename, content=content)

    def download(
        self, certificate_id: UUID, requester_id: UUID
    ) -> CertificateFile:
        """Authorize, serve stored bytes, or render on first access."""
        certificate = self._certificates.get_by_id(certificate_id)
        if certificate is None:
            raise NotFoundError("Certificate not found.")
        activity = self._activities.get(certificate.activity_id)
        if activity is None:
            raise NotFoundError("Certificate not found.")
        org_id = activity.org_id
        self._authorize(org_id, certificate.student_id, requester_id)
        stored = self._stored(certificate, certificate.serial_no)
        if stored is not None:
            return stored
        return self._generate(certificate, activity, org_id)
